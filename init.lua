-- Press <leader>l to launch live-server in the background

vim.keymap.set('n', '<leader>l', function()
  local file = vim.fn.expand '%:t' -- filename only (first-website.html)
  local dir = vim.fn.expand '%:p:h' -- directory path (/home/erik/fullstackopen)

  -- Kill any existing live-server
  vim.cmd '!pkill -f live-server > /dev/null 2>&1'

  -- Start live-server in the current file's directory and open the file
  vim.cmd('!nohup live-server ' .. dir .. ' --open=' .. file .. ' > /dev/null 2>&1 &')

  print('🚀 Live Server started in ' .. dir .. ' and opened ' .. file)
end, { noremap = true, silent = true, desc = 'Restart live-server for current HTML file' })
