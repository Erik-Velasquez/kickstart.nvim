local function set_indent(ft, width)
  vim.api.nvim_create_autocmd('FileType', {
    pattern = ft,
    callback = function()
      vim.bo.tabstop = width
      vim.bo.shiftwidth = width
      vim.bo.softtabstop = width
      vim.bo.expandtab = true
    end,
  })
end

